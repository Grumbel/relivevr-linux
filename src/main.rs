const H264_P_FRAME: &[u8] = &[
    0x00, 0x00, 0x00, 0x01, 0x41, 0x9a, 0x38, 0x13, 0xe0, 0x01, 0xfa, 0x58,
];

/// Real 1440×1440 baseline IDR access unit (SPS+PPS+SEI+IDR) from libx264.
fn h264_idr_au() -> &'static [u8] {
    H264_IDR_AU
}

fn h264_p_frame() -> &'static [u8] {
    H264_P_FRAME
}


fn make_video_frame_packet(frag_seq: u16, channel: u8, frame_num: u64, frm_type: u32, nals: &[u8]) -> Vec<u8> {
    let json = make_video_data_json(frame_num, frm_type, nals.len() as u32);
    let mut body = Vec::with_capacity(1 + json.len() + 1 + nals.len());
    body.push(1u8); // VideoData path in OnFrameReceived
    body.extend_from_slice(json.as_bytes());
    body.push(0u8); // NUL terminator for strlen
    body.extend_from_slice(nals);
    FragmentHeader::build_single(frag_seq, channel, &body)
}

fn parse_start_request(json: &str) -> (u32, u32, String, bool) {
    let mut w = 1440u32;
    let mut h = 1440u32;
    let mut codec = "avc".to_string();
    let mut nls = true;
    if let Some(v) = json.split("\"DisplayWidth\":").nth(1) {
        if let Some(num) = v.split(',').next() {
            if let Ok(n) = num.trim().parse() {
                w = n;
            }
        }
    }
    if let Some(v) = json.split("\"DisplayHeight\":").nth(1) {
        if let Some(num) = v.split(',').next() {
            if let Ok(n) = num.trim().parse() {
                h = n;
            }
        }
    }
    if let Some(v) = json.split("\"VideoCodec\":\"").nth(1) {
        if let Some(s) = v.split('"').next() {
            codec = s.to_string();
        }
    }
    if json.contains("\"NonLinearScalingSupported\":false") {
        nls = false;
    }
    (w, h, codec, nls)
}

fn is_our_payload(payload: &[u8]) -> bool {
    payload.windows(20).any(|w| w == b"relivevr-linux-probe")
}

fn parse_style(s: &str) -> ResponseStyle {
    match s {
        "minimal" => ResponseStyle::Minimal,
        "echo" => ResponseStyle::Echo,
        "full" => ResponseStyle::Full,
        _ => ResponseStyle::Full,
    }
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    let subscriber = FmtSubscriber::builder()
        .with_max_level(Level::DEBUG)
        .finish();
    tracing::subscriber::set_global_default(subscriber)?;

    let style = env::var("RELIVEVR_STYLE")
        .map(|s| parse_style(&s))
        .unwrap_or(ResponseStyle::Full);
    let type_byte: u8 = env::var("RELIVEVR_TYPE")
        .ok()
        .and_then(|s| s.parse().ok())
        .unwrap_or(TYPE_HELLO);
    let video_init_type: u8 = env::var("RELIVEVR_VIDEOINIT_TYPE")
        .ok()
        .and_then(|s| s.parse().ok())
        .unwrap_or(TYPE_VIDEO_INIT_DEFAULT);

    let bind_addr: SocketAddr = format!("0.0.0.0:{}", DEFAULT_PORT).parse()?;
    let socket = UdpSocket::bind(bind_addr).await?;
    socket.set_broadcast(true)?;

    info!("Listening on {}", bind_addr);
    info!(
        "Hello style={:?} type={}  VideoInit type={} (RELIVEVR_VIDEOINIT_TYPE)",
        style, type_byte, video_init_type
    );

    let socket = Arc::new(socket);
    let video_client: Arc<Mutex<Option<SocketAddr>>> = Arc::new(Mutex::new(None));
    let frame_seq = Arc::new(Mutex::new(1u16));
    let frame_num = Arc::new(Mutex::new(0u64));

    // Continuous ~60 fps stream once a client has started a session
    {
        let socket = Arc::clone(&socket);
        let video_client = Arc::clone(&video_client);
        let frame_seq = Arc::clone(&frame_seq);
        let frame_num = Arc::clone(&frame_num);
        tokio::spawn(async move {
            let mut tick = time::interval(Duration::from_millis(16)); // ~60 fps
            tick.set_missed_tick_behavior(time::MissedTickBehavior::Skip);
            let mut sent_idr = false;
            loop {
                tick.tick().await;
                let addr = { video_client.lock().await.clone() };
                let Some(addr) = addr else {
                    sent_idr = false;
                    continue;
                };
                let mut fseq = frame_seq.lock().await;
                let mut fnum = frame_num.lock().await;
                let nals = if !sent_idr || (*fnum % 60 == 0) {
                    sent_idr = true;
                    h264_idr_au()
                } else {
                    h264_p_frame()
                };
                let frm_type = if *fnum % 60 == 0 { 0 } else { 1 };
                let packet = make_video_frame_packet(*fseq, 1, *fnum, frm_type, nals);
                *fseq = fseq.wrapping_add(1);
                *fnum = fnum.wrapping_add(1);
                drop(fseq);
                drop(fnum);
                if let Err(e) = socket.send_to(&packet, addr).await {
                    warn!("stream send failed: {}", e);
                    *video_client.lock().await = None;
                }
            }
        });
    }

    let mut buf = vec![0u8; 65535];
    let mut reply_seq: u16 = 1;
    let mut announce_seq: u16 = 1;

    let mut announce = time::interval(Duration::from_secs(2));
    announce.set_missed_tick_behavior(time::MissedTickBehavior::Skip);

    loop {
        tokio::select! {
            _ = announce.tick() => {
                let json = make_hello_json(style);
                let packet = make_typed_json_packet(announce_seq, type_byte, &json);
                announce_seq = announce_seq.wrapping_add(1);
                let bcast = SocketAddr::from((Ipv4Addr::BROADCAST, DEFAULT_PORT));
                let _ = socket.send_to(&packet, bcast).await;
            }
            recv = socket.recv_from(&mut buf) => {
                match recv {
                    Ok((len, src)) => {
                        let data = &buf[..len];
                        let hdr = match FragmentHeader::parse(data) {
                            Some(h) => h,
                            None => {
                                info!("from {} len={} no-hdr {}", src, len, hex_preview(data, 32));
                                continue;
                            }
                        };
                        if len <= FRAG_HEADER_LEN {
                            continue;
                        }
                        let payload = &data[FRAG_HEADER_LEN..];
                        if is_our_payload(payload) {
                            continue;
                        }

                        let msg_type = payload[0];
                        info!(
                            "from {} seq={} field2={} off={} len={} flags=0x{:02x} pkt={}",
                            src, hdr.seq, hdr.field2, hdr.offset, hdr.length, hdr.flags, len
                        );

                        if payload.len() > 1 && (payload[1] == b'{' || payload[1] == b'[') {
                            if let Ok(s) = std::str::from_utf8(&payload[1..]) {
                                let s = s.trim_end_matches('\0');
                                info!("  type={} JSON: {}", msg_type, s);

                                match msg_type {
                                    TYPE_HELLO | TYPE_HELLO_DIRECT => {
                                        let resp_type = if env::var("RELIVEVR_TYPE").is_ok() {
                                            type_byte
                                        } else {
                                            TYPE_HELLO
                                        };
                                        let resp_style = if msg_type == TYPE_HELLO_DIRECT {
                                            ResponseStyle::Full
                                        } else {
                                            style
                                        };
                                        let json = make_hello_json(resp_style);
                                        let packet = make_typed_json_packet(reply_seq, resp_type, &json);
                                        reply_seq = reply_seq.wrapping_add(1);
                                        match socket.send_to(&packet, src).await {
                                            Ok(n) => info!(
                                                "  -> HelloResponse {}B style={:?} type={} (req {}) -> {}",
                                                n, resp_style, resp_type, msg_type, src
                                            ),
                                            Err(e) => warn!("  -> reply failed: {}", e),
                                        }
                                        // Decoder is created ~30ms after connect with empty MIME
                                        // (video/ + ""). Push VideoInit early; StartRequest refines.
                                        if msg_type == TYPE_HELLO_DIRECT {
                                            let vij = make_video_init_json(1440, 1440, "avc", true);
                                            let vp = make_typed_json_packet(reply_seq, video_init_type, &vij);
                                            reply_seq = reply_seq.wrapping_add(1);
                                            match socket.send_to(&vp, src).await {
                                                Ok(n) => info!(
                                                    "  -> early VideoInit {}B type={} -> {}",
                                                    n, video_init_type, src
                                                ),
                                                Err(e) => warn!("  -> early VideoInit failed: {}", e),
                                            }
                                        }
                                    }
                                    TYPE_START_REQUEST => {
                                        let (w, h, codec, nls) = parse_start_request(s);
                                        info!(
                                            "  StartRequest: {}x{} codec={} nls={}",
                                            w, h, codec, nls
                                        );
                                        // VideoInit works (ReInit(avc) confirmed). Keep a small set.
                                        let vij = make_video_init_json(w, h, &codec, nls);
                                        for &t in &[video_init_type, 2u8, 4, 8] {
                                            let packet = make_typed_json_packet(reply_seq, t, &vij);
                                            reply_seq = reply_seq.wrapping_add(1);
                                            let _ = socket.send_to(&packet, src).await;
                                            info!("  -> VideoInit plain type={}", t);
                                        }
                                        let mut stream_seq = 1u16;
                                        for channel in [0u8, 1, 2] {
                                            for &t in &[2u8, 4] {
                                                let packet = make_stream_json_packet(
                                                    reply_seq, stream_seq, channel, t, &vij,
                                                );
                                                reply_seq = reply_seq.wrapping_add(1);
                                                stream_seq = stream_seq.wrapping_add(1);
                                                let _ = socket.send_to(&packet, src).await;
                                                info!("  -> VideoInit stream ch={} type={}", channel, t);
                                            }
                                        }
                                        // Binary video on channel 1 (flags = channel)
                                        let idr = h264_idr_au();
                                        let p = h264_p_frame();
                                        let packet = make_video_frame_packet(reply_seq, 1, 0, 0, idr);
                                        reply_seq = reply_seq.wrapping_add(1);
                                        match socket.send_to(&packet, src).await {
                                            Ok(n) => info!("  -> VideoFrame IDR ch=1 {}B -> {}", n, src),
                                            Err(e) => warn!("  -> IDR failed: {}", e),
                                        }
                                        for i in 1u64..=30 {
                                            let packet = make_video_frame_packet(reply_seq, 1, i, 1, p);
                                            reply_seq = reply_seq.wrapping_add(1);
                                            let _ = socket.send_to(&packet, src).await;
                                        }
                                        info!("  -> sent IDR + 30 P-frames to {}", src);
                                        *video_client.lock().await = Some(src);
                                        info!("  -> continuous ~60fps stream armed for {}", src);
                                    }
                                    TYPE_DEVICE_CAPS => {
                                        info!("  device caps (no reply yet)");
                                    }
                                    9 => {
                                        // Observed after frames; treat as force-IDR / keepalive
                                        info!("  type=9 (force-IDR/keepalive?)");
                                        *video_client.lock().await = Some(src);
                                        let packet = make_video_frame_packet(
                                            reply_seq, 1, 0, 0, h264_idr_au(),
                                        );
                                        reply_seq = reply_seq.wrapping_add(1);
                                        let _ = socket.send_to(&packet, src).await;
                                        info!("  -> forced IDR -> {}", src);
                                    }
                                    other => {
                                        info!("  unhandled type {}", other);
                                    }
                                }
                            } else {
                                info!("  type={} hex: {}", msg_type, hex_preview(payload, 64));
                            }
                        } else {
                            info!("  type={} hex: {}", msg_type, hex_preview(payload, 64));
                        }
                    }
                    Err(e) => warn!("recv error: {}", e),
                }
            }
        }
    }
}
